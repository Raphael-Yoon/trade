def main():
    sys.stdout.reconfigure(encoding='utf-8')
    rec_json_file = PROJECT_ROOT / 'results' / 'sector_recommendations.json'
    
    if not rec_json_file.exists():
        print("[오류] sector_recommendations.json 파일이 존재하지 않습니다.")
        sys.exit(1)
        
    with open(rec_json_file, 'r', encoding='utf-8') as f:
        data = json.load(f)
        
    # JSON 파일 업데이트
    for r in data:
        code = r['code']
        if code in CUSTOM_ONE_LINERS:
            r['one_liner'] = CUSTOM_ONE_LINERS[code]
        if code in CUSTOM_REASONS:
            r['reason'] = CUSTOM_REASONS[code]
            
    with open(rec_json_file, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print("[+] JSON 파일에 고유 요약(one_liner) 및 분석 요약(reason) 반영 완료")

    # SQLite DB 업데이트
    print(f"[*] Updating SQLite DB: {SQLITE_PATH}")
    conn = sqlite3.connect(SQLITE_PATH)
    cursor = conn.cursor()
    
    for code in CUSTOM_ONE_LINERS.keys():
        one_liner = CUSTOM_ONE_LINERS[code]
        reason = CUSTOM_REASONS.get(code, '')
        cursor.execute("UPDATE tr_audit_recommendations SET one_liner = ?, reason = ? WHERE code = ?", (one_liner, reason, code))
        
    conn.commit()
    conn.close()
    print("[+] SQLite DB에 고유 요약(one_liner) 및 분석 요약(reason) 반영 완료")

if __name__ == '__main__':
    main()
